    static func contains(_ point: RouteCoordinate) -> Bool {
        guard (18...54).contains(point.latitude), (73...135).contains(point.longitude) else { return false }
        let x = point.longitude * 10_000
        let y = point.latitude * 10_000
        return mainland.contains { $0.contains(x: x, y: y) }
            && !excluded.contains { $0.contains(x: x, y: y) }
    }

    private struct Ring: Sendable {
        var vertices: [(x: Double, y: Double)]
        var minX: Double
        var maxX: Double
        var minY: Double
        var maxY: Double

        init(_ line: Substring) {
            let numbers = line.split(whereSeparator: \.isWhitespace).compactMap { Double($0) }
            vertices = stride(from: 0, to: numbers.count - 1, by: 2).map { (numbers[$0], numbers[$0 + 1]) }
            minX = vertices.map(\.x).min() ?? 0
            maxX = vertices.map(\.x).max() ?? 0
            minY = vertices.map(\.y).min() ?? 0
            maxY = vertices.map(\.y).max() ?? 0
        }

        func contains(x: Double, y: Double) -> Bool {
            guard x >= minX, x <= maxX, y >= minY, y <= maxY,
                  var previous = vertices.last else { return false }
            var inside = false
            for point in vertices {
                if (point.y > y) != (previous.y > y),
                   x < (previous.x - point.x) * (y - point.y) / (previous.y - point.y) + point.x {
                    inside.toggle()
                }
                previous = point
            }
            return inside
        }
